"""Bake the QR codes the Horrible Ideas quote cards print.

Reads data/jokes.json, collects every distinct url (plus the page's own
address as the fallback), and writes data/quote-qr.json: one module matrix
per url, each row a string of 0s and 1s. The page draws these straight onto
a canvas, so no QR encoder ships to the browser.

Run after adding a quote that carries a new url:

    python scripts/build-quote-qr.py

Needs the `qrcode` package (pip install qrcode).
"""
import json
from pathlib import Path

import qrcode

ROOT = Path(__file__).resolve().parent.parent
PAGE = "https://daatdata.net/horrible-ideas"


def matrix(url):
    qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
    qr.add_data(url)
    qr.make(fit=True)
    return ["".join("1" if cell else "0" for cell in row) for row in qr.get_matrix()]


def main():
    jokes = json.loads((ROOT / "data" / "jokes.json").read_text(encoding="utf-8"))["jokes"]
    urls = [PAGE] + sorted({j["url"] for j in jokes if j.get("url")})
    out = {"_README": "GENERATED by scripts/build-quote-qr.py. Do not hand-edit.",
           "fallback": PAGE,
           "codes": {u: matrix(u) for u in urls}}
    (ROOT / "data" / "quote-qr.json").write_text(
        json.dumps(out, indent=1), encoding="utf-8")
    print(f"wrote {len(urls)} codes")


if __name__ == "__main__":
    main()
